def ad_report(impressions, clicks, target=3.0):
    """計算點擊率 (CTR) 與是否達標，回傳 (ctr, passed)。"""
    if impressions == 0:
        return (None, False)
    if clicks == 0:
        ctr = 0.0
    else:
        ctr = (clicks / impressions) * 100
    passed = ctr >= target
    return (ctr, passed)


