def cumulative_spend(daily_spend, n):
    """以遞回計算前 n 天的累計廣告費（n 為非負整數）。"""
    if n <= 0 or not daily_spend:
        return 0
    if n > len(daily_spend):
        n = len(daily_spend)
    return cumulative_spend(daily_spend, n - 1) + daily_spend[n - 1]


