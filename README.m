## 程式逐步說明

### 1. 名稱整理

`event_name.strip().lower()` 先去掉頭尾空白，再轉成小寫，得到 `"weekend dinner"`。字串方法回傳新字串，因此用 `clean_event_name` 接住結果，原始 `event_name` 保持不變。

### 2. 餐費清理與型別轉換

三次 `replace()` 分別移除 `NT$`、逗號及半形空白，得到文字 `"1200"`。`float()` 將它轉成數值 `1200.0`，可以參與乘除計算。人數則用 `int(people)` 轉成整數。

本題使用題目提供的有效資料，不另外處理其他貨幣符號、無效輸入或零人分攤。

### 3. 計算順序

服務費以原始餐費計算，所以三組測試的服務費都是 `1200 × 0.10 = 120` 元。算出餐費加服務費後，再扣除該組折價券，最後除以人數。

### 4. 布林比較

`amount_per_person > budget_per_person` 直接產生 `True` 或 `False`，因此這題可以不使用 `if`。題目問的是「超過」，所以使用 `>`，每人費用等於預算時結果是 `False`。

### 5. 輸出格式

f-string 中的 `:.2f` 讓金額以小數點後兩位顯示。例如 `305.0` 顯示成 `305.00`。格式化產生顯示文字，原本的數值變數仍可繼續計算。本題保留原數值完成計算，再於最後輸出時格式化。


