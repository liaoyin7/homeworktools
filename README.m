## 兩題問答參考答案

### 問題一：為什麼 `"4"` 要先轉成數字？

`"4"` 是 `str`，`4` 才是 `int`。本題需要使用人數作為除數，計算每人分攤費用。Python 無法直接將餐費數值除以字串，因此先用 `int(people)` 得到整數 `4`，再參與計算。

文字外觀看起來像數字，並不代表 Python 已經將它當成數值。例如 `"4" + "1"` 會得到 `"41"`，而 `4 + 1` 才會得到 `5`。

### 問題二：如果先扣折價券，再計算服務費？

第一組先扣折價券，餐費基準會變成：

```text
1,200 − 100 = 1,100 元
```

再以 1,100 元計算 10% 服務費：

```text
服務費 = 1,100 × 0.10 = 110 元
應付總額 = 1,100 + 110 = 1,210 元
每人費用 = 1,210 ÷ 4 = 302.50 元
```

題目規定的計算則是：

```text
服務費 = 1,200 × 0.10 = 120 元
應付總額 = 1,200 + 120 − 100 = 1,220 元
每人費用 = 1,220 ÷ 4 = 305.00 元
```

兩種順序的服務費基準不同，相差 `100 × 0.10 = 10` 元。先折價再收服務費會少收 10 元，因此本題必須依題目規定，以原始餐費計算服務費。


