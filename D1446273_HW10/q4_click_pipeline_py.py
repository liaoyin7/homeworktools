def select_clicks(raw_clicks, min_clicks=10):
    """使用 map 與 filter 清理點擊字串並篩選達標素材，回傳 (numbers, qualified)。"""
    trimmed = map(lambda item: str(item).strip(), raw_clicks)
    non_empty = filter(None, trimmed)
    numbers = list(map(int, non_empty))
    qualified = list(filter(lambda val: val >= min_clicks, numbers))
    return (numbers, qualified)


if __name__ == "__main__":
    student_id = input("請輸入完整學號：").strip().upper()
    tail = student_id[-3:]
    a = int(student_id[-3])
    b = int(student_id[-2])
    c = int(student_id[-1])
    s = a + b + c

    min_clicks = 10 + 2 * c
    raw_clicks = [
        f" {10 * a} ",
        f"{10 * b}",
        "  ",
        "0",
        "",
        f" {10 * c + 5} ",
        f"{s * 2}",
    ]

    numbers, qualified = select_clicks(raw_clicks, min_clicks=min_clicks)

    print(f"學號：{student_id}（末三碼：{tail}，a={a}, b={b}, c={c}, s={s}）")
    print(f"合格門檻：{min_clicks}")
    print("清理後點擊數：", numbers)
    print("合格點擊數：", qualified)
    print(f"合格筆數：{len(qualified)}，合格合計：{sum(qualified)}")

    print("--- 合格素材點擊數排名（由高到低）---")
    for rank, clicks in enumerate(sorted(qualified, reverse=True), start=1):
        print(f"第 {rank} 名：{clicks}")

    print("--- 測試高門檻 min_clicks=100 ---")
    _, high_qualified = select_clicks(raw_clicks, min_clicks=100)
    if not high_qualified:
        print("無符合門檻的素材")
    else:
        print("合格點擊數：", high_qualified)