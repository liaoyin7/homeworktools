def collect_codes(raw_codes, saved=None):
    """清理優惠碼並去重，保留原有 saved 與首次出現順序，回傳新串列。"""
    result = []

    if saved is not None:
        for code in saved:
            cleaned = str(code).strip().upper()
            if cleaned and cleaned not in result:
                result.append(cleaned)

    for code in raw_codes:
        cleaned = str(code).strip().upper()
        if cleaned and cleaned not in result:
            result.append(cleaned)

    return result


